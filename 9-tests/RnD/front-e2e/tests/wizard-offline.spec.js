// E2E — TE-054: «визард без сети» — ожидаемое поведение по `04-architecture/read-paths.md` §1 п.1.
//
// Постановка @AR (`chat/ar.md` `[2026-11-15 04:55]`): «@TE: нужен сценарий „визард без сети“ —
// ожидаемое поведение по §1, а не „пусто и тихо“». §1 п.1 спеки: **молчаливый `catch` запрещён**;
// ошибка чтения обязана быть **отличима от «данных нет»**. Разрешено: явное состояние «не удалось»
// (неблокирующий бейдж/тост) либо отказ от предзаполнения **с сохранением формы** — но не тихий
// пустой список и не «визард вообще не открылся».
//
// Что проверяем (три утверждения, все — из спеки, а не из моего вкуса):
//   1. **Форма сохраняется:** при недоступном API визард ОТКРЫВАЕТСЯ. Исходная посылка («у
//      `DB.getAllPartners()` нет `.catch` ⇒ визард не открывается и ошибка не показана») **устарела**:
//      фронт уже обрабатывает отказ по каждому источнику и показывает видимую ошибку —
//      `8-front/js/app.js:672-682` (`src(...)` с fallback на каждый источник) и `:695-703`
//      (`reportReadFailure` → `showReadError`), `reopenWizard` — `:690-693` (`openWizardDegraded`).
//      Поэтому утверждение ниже — **защита от регресса**, а не описание текущего дефекта.
//      (формулировку уточнил @AR, `chat/ar.md 2026-11-10 19:52`; проверено чтением `origin`).
//   2. **Ошибка видна:** в визарде или тосте есть явный признак отказа (не удалось / ошибка / нет связи /
//      офлайн). Тихий `null`/`[]` этот пункт не проходит — он неотличим от «истории ещё нет».
//      Проверяется отказ **MV журнала**: партнёры и каталог приходят из `IndexedDB` (`DB.getAllPartners`,
//      `DB.getAllCatalog`), а не по HTTP, поэтому мокать их HTTP-запросы бессмысленно (@AR там же).
//   3. **Нет ложной подстановки:** при отказе предзаполнение не выдаётся за данные — выбранной карточки
//      партнёра по умолчанию нет (иначе пользователь видит «данные», которых не читали).
//
// Включается внешним признаком `XDIARY_READPATH_OFFLINE=1` (env), а не наблюдением за поведением.
// Флаг **уже выставлен в CI** (`.github/workflows/ci-front.yml:62`, `front-e2e-repeat.yml:47`), то есть
// спека не «зелёная на пустоте»: в CI она исполняется, а не скипается.
//
// MVP-истории: US-10 — ЧАСТИЧНО: проверяется офлайн-чтение, установка PWA браузером не проверяется
//   US-10 PWA и офлайн (частично, см. выше)
const { test, expect } = require('@playwright/test');
const { loginWithPin, reportStep, dumpViews } = require('./api');

const ENABLED = process.env.XDIARY_READPATH_OFFLINE === '1';

test('E2E: визард без сети — ошибка видна, форма сохранена (read-paths §1)', async ({ page }) => {
  test.skip(
    !ENABLED,
    'pending:FE-READPATH — ждём двух состояний на шаг (read-paths §3 п.1); включается XDIARY_READPATH_OFFLINE=1'
  );

  // Вход по PIN требует сети — поэтому сеть отключаем ПОСЛЕ логина, точечно: только MV журнала,
  // партнёры и каталог приходят из IndexedDB и не должны блокироваться (иначе проверим не то).
  await loginWithPin(page);
  await expect(page.locator('#view-journal')).toBeVisible({ timeout: 20000 });
  await reportStep(page, 'шаг 1: сессия получена, дальше — имитация «нет сети» для MV журнала');

  // Версия измеряемого фронта. Прогон поднимает СТАТИКУ из `8-front/` на момент запуска, поэтому
  // устаревший прогон может «краснеть» по уже исправленной причине: в `0.92` баннер вешался только
  // на `document.body` и не попадал под селектор ниже (`@FE 0.93`, `332027bc`). Версия НЕ влияет на
  // вердикт — она попадает в сообщения, чтобы красный был самообъясняющимся.
  // `APP_VERSION` живёт внутри IIFE, поэтому читаем исходник, а не `window`.
  const frontVersion = await page.evaluate(async () => {
    try {
      const src = await (await fetch('js/app.js')).text();
      const m = src.match(/APP_VERSION\s*=\s*"([\d.]+)"/);
      return m ? m[1] : '';
    } catch (e) {
      return '';
    }
  }).catch(() => '');
  await reportStep(page, 'шаг 1.1: версия измеряемого фронта = ' + (frontVersion || 'НЕ ИЗВЕСТНА'));
  const vNum = (v) => {
    const p = String(v || '').split('.').map((n) => parseInt(n, 10));
    return (p[0] || 0) * 1000 + (p[1] || 0);
  };
  const vHint = frontVersion && vNum(frontVersion) < vNum('0.93')
    ? ' (прогон до 0.93 объясняется известным дефектом 0.92: баннер вне селектора спеки)'
    : '';

  // Только MV журнала: партнёры/каталог идут из IndexedDB, их HTTP-мок ничего не проверял (@AR 19:52).
  await page.route('**/api/v1/journal/**', (route) => route.abort('failed'));
  try {
    await page.click('#btn-new');
    await dumpViews(page, 'wizard-offline: после нажатия «+» без сети');

    // 1. Форма сохраняется: визард обязан открыться, а не «молча ничего».
    await expect(page.locator('#view-wizard'),
      'визард не открылся при отказе read-path; версия фронта = ' + (frontVersion || '?') + vHint)
      .toBeVisible({ timeout: 20000 });

    // 2. Ошибка обязана быть видна и отличима от «данных нет».
    const errorSignal = page.locator('#toast, #view-wizard').filter({
      hasText: /(не удалось|ошибк|нет связи|офлайн|offline)/i,
    });
    await expect(errorSignal.first(),
      'нет видимого признака отказа чтения (read-paths §1 п.1); версия фронта = ' +
      (frontVersion || '?') + vHint)
      .toBeVisible({ timeout: 20000 });

    // 3. Предзаполнение не выдаётся за прочитанные данные.
    await expect(page.locator('#w-partner-grid .partner-card.selected'),
      'ложная подстановка партнёра при отказе read-path; версия фронта = ' + (frontVersion || '?') + vHint)
      .toHaveCount(0, { timeout: 10000 });
  } finally {
    await page.unroute('**/api/v1/journal/**').catch(() => {});
  }
});
